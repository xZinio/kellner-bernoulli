#!/usr/bin/env python3
# Generates KellnerBernoulli/Data.lean: lists of primes used as certificates.  The data need not be
# trusted: every list is checked by Lean's kernel (see Finite.lean).
import bisect, math, sys
def primes(n):
    s = bytearray([1]) * (n + 1); s[0:2] = b'\0\0'
    for i in range(2, int(n ** .5) + 1):
        if s[i]: s[i*i::i] = bytearray(len(s[i*i::i]))
    return [i for i in range(n + 1) if s[i]]
PR = primes(4_100_000)
trial = [p for p in PR if p < 2030]                 # trial divisors, 2029^2 > 4.1e6
chain = [p for p in PR if 43 <= p <= 10400]         # primes for the chain, n < 10^8
# sparse list r_0 < r_1 < ... with (r_{i+16}-r_i)^2 < 4 r_{i+16}, from below 10^4 to beyond 4*10^6
G = 16
def build(start, stop):
    out = [start]
    while out[-1] < stop:
        r = out[-1]
        # largest next prime such that the window ending there is fine, and not too greedy
        g = int(0.1245 * math.isqrt(r))
        i = bisect.bisect_right(PR, r + max(g, 2)) - 1
        if PR[i] <= r: i = bisect.bisect_right(PR, r)
        out.append(PR[i])
    return out
def ok(l): return all(4 * l[i + G] > (l[i + G] - l[i]) ** 2 for i in range(len(l) - G))
def firstbad(l):
    for i in range(len(l) - G):
        if not 4 * l[i + G] > (l[i + G] - l[i]) ** 2: return i
    return None
start = 9973
win = build(start, 4_012_000)
# repair: shrink steps inside bad windows by inserting skipped primes
it = 0
S = set(win)
while True:
    l = sorted(S); b = firstbad(l)
    if b is None: break
    # insert all primes in the window that are not used, largest gaps first
    w = l[b:b + G + 1]
    gaps = sorted(((w[i + 1] - w[i], i) for i in range(G)), reverse=True)
    done = False
    for g, i in gaps:
        j = bisect.bisect_right(PR, w[i]); k = bisect.bisect_left(PR, w[i + 1])
        if j < k: S.add(PR[(j + k) // 2]); done = True; break
    if not done: print('cannot repair at', w[0]); sys.exit(1)
    it += 1
win = sorted(S)
assert ok(win) and all(p in set(PR) for p in win)
print('trial', len(trial), 'chain', len(chain), 'window', len(win), 'repairs', it, 'range', win[0], win[-17], win[-1], file=sys.stderr)
def emit(name, l, doc):
    s = '/-- %s -/\ndef %s : List ℕ := [\n' % (doc, name)
    row = ''; rows = []
    for x in l:
        t = '%d, ' % x
        if len(row) + len(t) > 98: rows.append(row.rstrip()); row = ''
        row += t
    rows.append(row.rstrip().rstrip(','))
    return s + '\n'.join(rows) + ']\n\n'
def main():
    o = '/-\nThis file was generated by `scripts/gen_data.py`. Nothing in it is trusted: the lists are checked by\nthe kernel in `Finite.lean`.\n-/\n'
    o += 'import Mathlib.Data.Nat.Notation\n\nnamespace KellnerBernoulli.Data\n\nset_option maxRecDepth 100000\n\n'
    o += emit('trial', trial, 'All primes below 2030.')
    o += emit('chain', chain, 'Primes between 43 and 10400.')
    C = 500
    blocks = [win[i:i + C + G] for i in range(0, len(win) - G, C)]
    for i, b in enumerate(blocks):
        o += emit('window%d' % i, b, 'Block %d of the sparse list of primes.' % i)
    o += '/-- The blocks; consecutive blocks overlap in 16 elements. -/\ndef windows : List (List ℕ) := [\n  ' + ', '.join('window%d' % i for i in range(len(blocks))) + ']\n\n'
    o += 'end KellnerBernoulli.Data\n'
    open('KellnerBernoulli/Data.lean', 'w').write(o)
    print('blocks', len(blocks), 'bytes', len(o), file=sys.stderr)
main()
